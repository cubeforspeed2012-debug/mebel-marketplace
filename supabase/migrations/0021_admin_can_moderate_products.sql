-- Администратор не мог одобрить работу.
--
-- Права на работы были такие: мастер распоряжается своими, гость и
-- пользователь видят активные, администратор видит все. Менять чужие
-- работы администратору никто не разрешил — раньше это было незаметно,
-- потому что работы и так попадали в каталог сами.
--
-- Теперь, когда работа ждёт проверки, это стало дырой навылет: кнопка
-- «В каталог» молча меняла ноль строк, и очередь не разбиралась бы
-- никогда. Ошибки при этом не видно — правило доступа просто не находит
-- ни одной строки, которую можно тронуть.
create policy "admin moderates products"
  on public.products
  for update
  to authenticated
  using (public.is_admin())
  with check (public.is_admin());
