--
-- Задумано было так: мастер меняет снимки — работа уходит на повторную
-- проверку. На деле два сторожа мешали друг другу. Триггер на фотографиях
-- снимал отметку «проверено», но тут же срабатывал сторож самой работы
-- и возвращал отметку обратно — он на то и поставлен, чтобы мастер не мог
-- её себе поднять, и отличить свой же сброс от чужой попытки не умел.
--
-- В итоге схема обхода оставалась открытой: выложить настоящую кухню,
-- дождаться одобрения, а потом подменить снимки на что угодно. Причём
-- это худший вариант подмены: в каталоге люди смотрят на фотографии,
-- а не читают описания.
