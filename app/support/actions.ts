'use server'

import { askGroq } from '@/lib/groq'
import { notifyTelegram } from '@/lib/telegram'
import { createClient } from '@/lib/supabase/server'

export type ChatMessage = { role: 'user' | 'assistant'; text: string }
export type SupportReply = { text?: string; error?: string }
export type TicketState = { ok?: boolean; error?: string }

/**
 * Что помощник знает о сайте. Это не «будь вежливым ассистентом», а
 * конкретные факты: как устроена регистрация, почему работа «на проверке»,
 * куда нажать. Без этого модель отвечает общими словами про «обратитесь
 * в службу поддержки» — а она и есть служба поддержки.
 */
const SYSTEM = `Ты — поддержка сайта Mebel (top-mebel.uz), площадки мебельных мастеров и фабрик Ташкента. Отвечай по-русски, коротко и по делу, 2–5 предложений. Без эмодзи, без приветствий вроде «Здравствуйте!» в каждом сообщении, без markdown.

КАК УСТРОЕН САЙТ
- Два вида людей: покупатели (ищут мебель, звонят мастеру напрямую) и мастера (мастерские и фабрики, выкладывают работы).
- Площадка бесплатная: 0% комиссии, размещение бесплатно. Деньги за мебель мастер и клиент передают друг другу напрямую, сайт в сделке не участвует.
- Регистрация: кнопка «Войти» → вкладка «Регистрация» → имя, телефон, почта, пароль. Или через Google.
- Мастер после регистрации попадает в форму «Моя мастерская»: название, телефон для клиентов, район, чем занимается, описание, логотип. Без мастерской в каталоге его нет.
- Мастерская после заполнения идёт на проверку администратору — обычно до одного дня. Пока проверяют, в каталоге её нет, в кабинете написано «На проверке».
- Работы (мебель) мастер добавляет в разделе «Мои работы». Каждая новая работа тоже проходит проверку — статус «На проверке». Если после одобрения поменять название, цену, описание или фото — работа снова уйдёт на проверку. Это защита от подмены.
- Статус «Скрыто» — мастер сам спрятал работу кнопкой «Спрятать». Нажать «Показать» можно только у проверенной работы.
- Заявки: клиент оставляет заявку на странице мастера, она появляется в кабинете в разделе «Заказы». Если мастер подключил Telegram — заявка приходит сообщением в бот @mebel717_bot.
- Telegram подключается в кабинете: кнопка «Подключить Telegram» → открывается бот → нажать Start. Ссылка живёт 15 минут.
- Подтверждение номера: в кабинете или в форме мастерской кнопка «Подтвердить номер» → бот → кнопка Telegram «Поделиться номером». Подтвердить можно только свой номер, тот, на который зарегистрирован Telegram. Если поменять номер в профиле — подтверждение снимается.
- Мини-приложение в Telegram: только вход (Google или почта), регистрации там нет — она на сайте. Показывает аналитику и просмотры.
- Отзывы: оставить может вошедший пользователь на странице мастерской. Рейтинг считается автоматически.
- Забыли пароль: на странице входа «Забыли пароль?» или вход по коду из письма.
- Кнопка «Показать номер» на странице мастера открывает телефон; сайт считает, сколько людей хотели позвонить.
- Продвижение («поднять в каталоге») и оплата пока не запущены.

КАК ОТВЕЧАТЬ
- Сначала конкретный шаг, куда нажать. Потом, если нужно, почему так.
- Не выдумывай функций, которых нет в списке выше. Если не знаешь — так и скажи и предложи позвать администратора кнопкой под чатом.
- Если человек описывает ошибку, поломку, потерю денег, обман, или просит удалить аккаунт — коротко ответь и посоветуй нажать «Позвать администратора».
- Никогда не проси пароль, код из СМС, номер карты.`

/** Один ответ помощника на всю переписку. */
export async function askSupport(history: ChatMessage[]): Promise<SupportReply> {
  // Держим разговор в рамках: помощник бесплатный, но лимит запросов общий
  const trimmed = history.slice(-12).map((m) => ({
    role: m.role,
    text: String(m.text ?? '').slice(0, 1200),
  }))
  const last = trimmed[trimmed.length - 1]
  if (!last || last.role !== 'user' || !last.text.trim()) {
    return { error: 'Напишите вопрос' }
  }

  // Groq принимает одну пару system/user — складываем переписку в одно письмо
  const conversation = trimmed
    .map((m) => (m.role === 'user' ? `Пользователь: ${m.text}` : `Поддержка: ${m.text}`))
    .join('\n\n')

  const result = await askGroq(SYSTEM, `${conversation}\n\nПоддержка:`)
  if (result.error) return { error: result.error }

  return { text: (result.text ?? '').replace(/^Поддержка:\s*/i, '').trim() }
}

/**
 * Помощник не справился — зовём человека. Переписка уходит целиком,
 * чтобы администратор не переспрашивал, а сразу видел, что случилось.
 */
export async function callAdmin(
  history: ChatMessage[],
  contact: string,
  page: string,
): Promise<TicketState> {
  const supabase = await createClient()
  const transcript = history.slice(-40).map((m) => ({
    role: m.role,
    text: String(m.text ?? '').slice(0, 1200),
  }))

  const { data: id, error } = await supabase.rpc('create_support_ticket', {
    p_contact: contact.trim().slice(0, 200),
    p_page: page.slice(0, 200),
    p_transcript: transcript,
  })

  if (error) return { error: 'Не получилось отправить. Попробуйте ещё раз' }

  // Если у администратора настроен Telegram — сообщаем сразу.
  // Не настроен — обращение всё равно лежит в админке.
  const adminChat = process.env.ADMIN_TELEGRAM_CHAT_ID
  if (adminChat) {
    const lastUser = [...transcript].reverse().find((m) => m.role === 'user')?.text ?? ''
    await notifyTelegram(
      adminChat,
      [
        `<b>Обращение в поддержку #${id}</b>`,
        contact ? `Связь: ${contact}` : 'Связь: не указана',
        '',
        lastUser.slice(0, 500),
      ].join('\n'),
    )
  }

  return { ok: true }
}
